using System.Globalization;
using System.Reflection;
using System.Text.RegularExpressions;
using Microsoft.EntityFrameworkCore;
using Survsys.Data;
using Survsys.Messaging;
using MessagingGuideLink = Survsys.Messaging.GuideLink;
using MessagingPhinVariable = Survsys.Messaging.PhinVariable;

namespace Survsys.Api;

/// <summary>
/// One message a notification build raised: the PHIN variable it is about, or
/// null where it is about the build as a whole, what was said, and how severe
/// it is.
/// </summary>
public sealed record NotificationBuildMessage(string? PhinVar, string Message, RuleSetMessageKind Severity);

/// <summary>
/// What building a case's notification came to: the case's record number, the
/// guide it was built under, the generated ER7, and every message raised on
/// the way. <paramref name="Message"/> is null when an error stopped the build.
/// </summary>
public sealed record NotificationBuild(
    string RecordNumber,
    int? GuideId,
    string? Message,
    IReadOnlyList<NotificationBuildMessage> Messages);

/// <summary>
/// Builds a case's ORU^R01 notification from the database: the case flattened
/// into an <see cref="EpiTraxRecord"/>, its guide's PHIN variables from
/// <see cref="PhinVariableMapper"/>, each formatted by its rule set, and the
/// message generated by <see cref="OruR01Generator"/>.
/// </summary>
/// <remarks>
/// The legacy NMI <c>xmlGenerator</c> described in
/// <c>../nedss/docs/business-logic/NMI_XML_GENERATION.md</c>, kept to what the
/// tables here hold. The messaging module sees no database, so the projection
/// of the Survsys.Data tables into its records is here.
///
/// The record's core fields are the case's and the person's scalar columns
/// under their snake_case names, the person's prefixed <c>person_</c>, with
/// <c>cdc_first_sent_at</c> from the case's first accepted export. Its Lab
/// dataset is one row per lab test result (the lab's, test's and result's
/// columns together), and its Vaccine and Treatment datasets one row per
/// vaccination and treatment; there is no travel table, so Travel is empty.
/// A variable whose rule set data names a <c>dataSet</c> is formatted per row
/// of that dataset by <see cref="RepeatingGroupProcessor"/>, each row's values
/// carrying its instance number as the OBX sub-id. There are no value set
/// tables yet, so a rule set's value set is empty.
/// </remarks>
public sealed partial class NotificationMessageBuilder(SurvsysDbContext database)
{
    private const string Version = "2.5.1";
    private const string ProfileId = "NOTF_ORU_v3.0";
    private const string DataSetKey = "dataSet";

    // The notification status variable, and the status a retraction sends:
    // "results cannot be obtained", which CDC reads as the notification withdrawn.
    private const string NotificationStatusVariable = "NOT118";
    private const string RetractedStatus = "X";

    private static readonly NotificationIdentifier SendingApp = new("Survsys", "2.16.840.1.114222.4.3.3.2.1", "ISO");
    private static readonly NotificationIdentifier SendingFacility = new("CTDPH", "2.16.840.1.114222.4.1.3650", "ISO");
    private static readonly NotificationIdentifier ReceivingApp = new("CDC", "2.16.840.1.114222.4.3.2.10", "ISO");
    private static readonly NotificationIdentifier ReceivingFacility = new("CDC", "2.16.840.1.114222.4.1.3650", "ISO");

    /// <summary>
    /// Builds the notification of case <paramref name="personConditionId"/>
    /// under <paramref name="processingId"/> (<c>P</c>, <c>T</c> or <c>D</c>),
    /// sent at <paramref name="at"/>; where <paramref name="retract"/> is set,
    /// with its notification status NOT118 set to <c>X</c>, which retracts a
    /// notification CDC accepted before.
    /// </summary>
    public async Task<NotificationBuild> Build(
        int personConditionId,
        string processingId,
        DateTimeOffset at,
        CancellationToken cancellationToken,
        bool retract = false)
    {
        var personCondition = await database.PersonConditions.AsNoTracking()
            .SingleAsync(item => item.Id == personConditionId, cancellationToken);
        var messages = new List<NotificationBuildMessage>();

        var guideId = await database.ConditionDetails.AsNoTracking()
            .Where(detail => detail.ConditionId == personCondition.ConditionId)
            .Select(detail => (int?)detail.GuideId)
            .SingleOrDefaultAsync(cancellationToken);
        if (guideId is null)
        {
            messages.Add(new(null, "The case's condition has no notification guide.", RuleSetMessageKind.Error));
            return new NotificationBuild(personCondition.RecordNumber, null, null, messages);
        }

        var definitions = await database.PhinVariables.AsNoTracking().ToListAsync(cancellationToken);
        var mapper = new PhinVariableMapper(new PhinVariableCatalog(
            definitions.Select(item => new MessagingPhinVariable(
                item.PhinVar, item.Description, item.Hl7DataType, item.Priority, item.CodeSystem)).ToList(),
            [new ConditionGuide(personCondition.ConditionId, guideId.Value)],
            await database.GuidePhinVariables.AsNoTracking()
                .Select(item => new GuideVariable(item.GuideId, item.PhinVar)).ToListAsync(cancellationToken),
            await database.GuideLinks.AsNoTracking()
                .Select(item => new MessagingGuideLink(item.GuideId, item.LinkedGuideId)).ToListAsync(cancellationToken)));
        var variables = mapper.MapForCondition(personCondition.ConditionId);
        var definitionsByVar = definitions.ToDictionary(item => item.PhinVar, StringComparer.Ordinal);

        var ruleSets = await LoadRuleSets(
            variables.Select(variable => definitionsByVar[variable.PhinVar]).ToList(), cancellationToken);
        var record = await LoadRecord(personCondition, cancellationToken);
        var formatters = Formatters(new FixedTime(at));

        var values = new List<NotificationValue>();
        var groups = new Dictionary<string, List<RepeatingGroupVariable>>(StringComparer.Ordinal);
        foreach (var variable in variables)
        {
            var definition = definitionsByVar[variable.PhinVar];
            if (definition.RuleSetConfigId is not { } configId
                || !ruleSets.TryGetValue(configId, out var ruleSet)
                || !formatters.TryGetValue(ruleSet.TypeLabel, out var formatter))
            {
                messages.Add(new(variable.PhinVar, "No rule set formats this variable.", RuleSetMessageKind.Warning));
                continue;
            }

            if (ruleSet.Data.GetValueOrDefault(DataSetKey) is { Length: > 0 } dataSet)
            {
                if (!groups.TryGetValue(dataSet, out var group))
                {
                    groups[dataSet] = group = [];
                }

                group.Add(new RepeatingGroupVariable(variable.PhinVar, ruleSet, formatter));
                continue;
            }

            Collect(variable, formatter.Format(ruleSet, record), 0, values, messages);
        }

        var processor = new RepeatingGroupProcessor();
        var variablesByVar = variables.ToDictionary(item => item.PhinVar, StringComparer.Ordinal);
        foreach (var (dataSet, groupVariables) in groups)
        {
            IReadOnlyList<RepeatingGroupInstance> instances;
            try
            {
                instances = processor.Process(new RepeatingGroup(dataSet, dataSet, groupVariables), record);
            }
            catch (ArgumentException exception)
            {
                messages.Add(new(null, exception.Message, RuleSetMessageKind.Error));
                continue;
            }

            foreach (var instance in instances)
            {
                foreach (var value in instance.Values)
                {
                    Collect(variablesByVar[value.PhinVar], value.Formatted, instance.InstanceNumber, values, messages);
                }
            }
        }

        if (messages.Any(message => message.Severity == RuleSetMessageKind.Error))
        {
            return new NotificationBuild(personCondition.RecordNumber, guideId, null, messages);
        }

        if (retract)
        {
            values.RemoveAll(value => value.PhinVar == NotificationStatusVariable);
            values.Add(new NotificationValue(
                NotificationStatusVariable, "Notification Result Status", "ID", RetractedStatus, RetractedStatus,
                null, null, 0));
        }

        var guideName = await database.NotificationGuides.AsNoTracking()
            .Where(guide => guide.Id == guideId)
            .Select(guide => guide.Name)
            .SingleOrDefaultAsync(cancellationToken);
        var header = new NotificationHeader(
            SendingApp,
            SendingFacility,
            ReceivingApp,
            ReceivingFacility,
            at,
            processingId,
            Version,
            ProfileId,
            string.Create(CultureInfo.InvariantCulture, $"SURVSYS{at:yyyyMMddHHmmss}{personConditionId}"));
        var message = new OruR01Generator().Generate(
            new OruR01GenerationInput(header, guideName ?? ProfileId, values));

        return new NotificationBuild(personCondition.RecordNumber, guideId, message, messages);
    }

    /// <summary>
    /// The formatted results of one variable as notification values, and the
    /// messages they carry as build messages.
    /// </summary>
    private static void Collect(
        MessagingPhinVariable variable,
        IReadOnlyList<RuleSetFormattedData> formatted,
        int subId,
        List<NotificationValue> values,
        List<NotificationBuildMessage> messages)
    {
        foreach (var result in formatted)
        {
            if (result.Message is { } text)
            {
                messages.Add(new(variable.PhinVar, text, result.MessageKind ?? RuleSetMessageKind.Info));
            }

            if (string.IsNullOrWhiteSpace(result.Value) && string.IsNullOrWhiteSpace(result.Code))
            {
                continue;
            }

            var valueType = variable.Hl7DataType ?? (string.IsNullOrEmpty(result.Code) ? "ST" : "CWE");
            values.Add(new NotificationValue(
                variable.PhinVar,
                variable.Description,
                valueType,
                result.Value,
                result.Code,
                result.CodeSystemOid,
                result.OtherSpecified,
                subId));
        }
    }

    /// <summary>The formatter of each rule set label.</summary>
    private static Dictionary<string, IRuleSetFormatter> Formatters(TimeProvider time) =>
        new(StringComparer.Ordinal)
        {
            ["staticValue"] = new StaticValueFormatter(time),
            ["cdcFirstSent"] = new CdcFirstSentFormatter(time),
            ["cdcDiseaseId"] = new CdcDiseaseIdFormatter(),
            ["fieldValueMap"] = new FieldValueMapFormatter(),
            ["conditionMap"] = new ConditionMapFormatter(),
            ["notificationStatusResponse"] = new NotificationStatusResponseFormatter(),
            ["repeatingGroup"] = new RepeatingGroupFormatter(),
        };

    /// <summary>The rule set configs <paramref name="variables"/> name, loaded, by config id.</summary>
    private async Task<Dictionary<int, LoadedRuleSet>> LoadRuleSets(
        IReadOnlyList<Data.PhinVariable> variables, CancellationToken cancellationToken)
    {
        var configIds = variables
            .Where(variable => variable.RuleSetConfigId is not null)
            .Select(variable => variable.RuleSetConfigId!.Value)
            .Distinct()
            .ToList();
        var labels = await database.RuleSets.AsNoTracking()
            .ToDictionaryAsync(ruleSet => ruleSet.Id, ruleSet => ruleSet.Label, cancellationToken);
        var configs = await database.RuleSetConfigs.AsNoTracking()
            .Where(config => configIds.Contains(config.Id)).ToListAsync(cancellationToken);
        var fields = (await database.RuleSetFields.AsNoTracking()
            .Where(field => configIds.Contains(field.RuleSetConfigId)).OrderBy(field => field.Id)
            .ToListAsync(cancellationToken)).ToLookup(field => field.RuleSetConfigId);
        var data = (await database.RuleSetData.AsNoTracking()
            .Where(item => configIds.Contains(item.RuleSetConfigId))
            .ToListAsync(cancellationToken)).ToLookup(item => item.RuleSetConfigId);
        var valueMaps = (await database.RuleSetValueMaps.AsNoTracking()
            .Where(map => configIds.Contains(map.RuleSetConfigId)).OrderBy(map => map.Id)
            .ToListAsync(cancellationToken)).ToLookup(map => map.RuleSetConfigId);
        var expressions = await database.RuleSetExpressions.AsNoTracking()
            .Where(expression => configIds.Contains(expression.RuleSetConfigId))
            .ToListAsync(cancellationToken);
        var expressionIds = expressions.Select(expression => expression.Id).ToList();
        var conditions = (await database.RuleSetExpressionConditions.AsNoTracking()
            .Where(condition => expressionIds.Contains(condition.RuleSetExpressionId)).OrderBy(condition => condition.Id)
            .ToListAsync(cancellationToken)).ToLookup(condition => condition.RuleSetExpressionId);
        var expressionsByConfig = expressions.ToLookup(expression => expression.RuleSetConfigId);

        // A config belongs to the rule set its variables name; the first one decides its label.
        var labelByConfig = variables
            .Where(variable => variable.RuleSetConfigId is not null && variable.RuleSetId is not null)
            .GroupBy(variable => variable.RuleSetConfigId!.Value)
            .ToDictionary(group => group.Key, group => labels.GetValueOrDefault(group.First().RuleSetId!.Value));

        var loaded = new Dictionary<int, LoadedRuleSet>();
        foreach (var config in configs)
        {
            if (labelByConfig.GetValueOrDefault(config.Id) is not { } label)
            {
                continue;
            }

            loaded[config.Id] = new LoadedRuleSet(
                label,
                config.FormatType,
                config.Repeating,
                config.ValueSetName,
                fields[config.Id].Select(field => field.Field).ToList(),
                data[config.Id].GroupBy(item => item.DataName, StringComparer.Ordinal)
                    .ToDictionary(group => group.Key, group => group.First().DataValue, StringComparer.Ordinal),
                valueMaps[config.Id].Select(map => new ValueMapping(map.ValueFrom, map.ValueTo, map.OtherSpecified)).ToList(),
                expressionsByConfig[config.Id]
                    .Select(expression => new ConditionExpression(
                        expression.Value,
                        expression.OtherSpecified,
                        expression.ExecutionOrder,
                        conditions[expression.Id]
                            .Select(condition => new ExpressionCondition(
                                condition.Field, condition.Operator, condition.Value, condition.AndOr, condition.ValueIsField))
                            .ToList()))
                    .ToList(),
                []);
        }

        return loaded;
    }

    /// <summary>The case as an EpiTrax record: its core fields and its Lab, Vaccine and Treatment datasets.</summary>
    private async Task<EpiTraxRecord> LoadRecord(PersonCondition personCondition, CancellationToken cancellationToken)
    {
        var person = await database.Persons.AsNoTracking()
            .SingleAsync(item => item.Id == personCondition.PersonId, cancellationToken);
        var firstSentAt = await database.CdcExportLog.AsNoTracking()
            .Where(entry => entry.PersonConditionId == personCondition.Id && entry.SentAt != null)
            .MinAsync(entry => entry.SentAt, cancellationToken);

        var fields = new Dictionary<string, string?>(StringComparer.Ordinal);
        Flatten(personCondition, string.Empty, fields);
        Flatten(person, "person_", fields);
        fields["cdc_first_sent_at"] = firstSentAt is { } sent
            ? DateTime.SpecifyKind(sent, DateTimeKind.Utc).ToString("O", CultureInfo.InvariantCulture)
            : null;

        var linkedLabIds = database.PersonConditionLabs
            .Where(link => link.PersonConditionId == personCondition.Id)
            .Select(link => link.LabId);
        var labRows = await (
            from lab in database.Labs.AsNoTracking()
            where lab.PersonConditionId == personCondition.Id || linkedLabIds.Contains(lab.Id)
            join test in database.LabTests.AsNoTracking() on lab.Id equals test.LabId
            join result in database.LabTestResults.AsNoTracking() on test.Id equals result.LabTestId
            orderby lab.Id, test.Id, result.Id
            select new { lab, test, result }).ToListAsync(cancellationToken);
        var vaccines = await database.PersonVaccines.AsNoTracking()
            .Where(item => item.PersonConditionId == personCondition.Id).OrderBy(item => item.Id)
            .ToListAsync(cancellationToken);
        var treatments = await database.PersonTreatments.AsNoTracking()
            .Where(item => item.PersonConditionId == personCondition.Id).OrderBy(item => item.Id)
            .ToListAsync(cancellationToken);

        return new EpiTraxRecord(fields, new Dictionary<string, IReadOnlyList<DatasetRow>>(StringComparer.Ordinal)
        {
            ["Lab"] = labRows.Select(row => Row(row.lab, row.test, row.result)).ToList(),
            ["Vaccine"] = vaccines.Select(item => Row(item)).ToList(),
            ["Treatment"] = treatments.Select(item => Row(item)).ToList(),
        });
    }

    /// <summary>One dataset row from the scalar columns of <paramref name="entities"/>, later ones winning.</summary>
    private static DatasetRow Row(params object[] entities)
    {
        var fields = new Dictionary<string, string?>(StringComparer.Ordinal);
        foreach (var entity in entities)
        {
            Flatten(entity, string.Empty, fields);
        }

        return new DatasetRow(fields);
    }

    /// <summary>Writes each scalar property of <paramref name="entity"/> into <paramref name="fields"/> under its snake_case name.</summary>
    private static void Flatten(object entity, string prefix, Dictionary<string, string?> fields)
    {
        foreach (var property in entity.GetType().GetProperties(BindingFlags.Public | BindingFlags.Instance))
        {
            var type = Nullable.GetUnderlyingType(property.PropertyType) ?? property.PropertyType;
            if (type != typeof(string) && !type.IsPrimitive && !type.IsEnum
                && type != typeof(decimal) && type != typeof(DateOnly)
                && type != typeof(DateTime) && type != typeof(DateTimeOffset))
            {
                continue;
            }

            fields[prefix + SnakeCase(property.Name)] = property.GetValue(entity) switch
            {
                null => null,
                DateOnly date => date.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
                DateTime moment => moment.ToString("O", CultureInfo.InvariantCulture),
                DateTimeOffset moment => moment.ToString("O", CultureInfo.InvariantCulture),
                IFormattable formattable => formattable.ToString(null, CultureInfo.InvariantCulture),
                var value => value.ToString(),
            };
        }
    }

    private static string SnakeCase(string name) => WordBoundary().Replace(name, "_$1").ToLowerInvariant();

    [GeneratedRegex("(?<=[a-z0-9])([A-Z])")]
    private static partial Regex WordBoundary();

    /// <summary>A clock stopped at the build's moment, so dates a formatter writes agree with the header.</summary>
    private sealed class FixedTime(DateTimeOffset at) : TimeProvider
    {
        public override DateTimeOffset GetUtcNow() => at;
    }
}
